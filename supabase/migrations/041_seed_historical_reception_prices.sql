-- 1. Remove static default_unit_price_ht column from products table if it exists
alter table if exists products
  drop column if exists default_unit_price_ht cascade;

-- 2. Recreate product_catalog view without static default_unit_price_ht
create or replace view product_catalog as
select
  p.id,
  p.code,
  p.name,
  p.type,
  p.category,
  p.unit,
  case
    when p.type = 'raw' then 'not_required'::recipe_status
    when exists (
      select 1 from recipes r
      where r.product_id = p.id and r.is_active = true
    ) then 'active'::recipe_status
    else 'missing'::recipe_status
  end as recipe_status,
  coalesce((
    select count(*)::integer
    from recipes r
    join recipe_components rc on rc.recipe_id = r.id
    where r.product_id = p.id and r.is_active = true
  ), 0) as component_count,
  p.updated_at,
  p.lot_zone,
  p.lot_code,
  p.created_by,
  creator.display_name as created_by_name,
  creator.email as created_by_email,
  p.updated_by,
  updater.display_name as updated_by_name,
  updater.email as updated_by_email,
  active_recipe.created_by as schema_updated_by,
  schema_actor.display_name as schema_updated_by_name,
  schema_actor.email as schema_updated_by_email,
  active_recipe.created_at as schema_updated_at
from products p
left join profiles creator on creator.user_id = p.created_by
left join profiles updater on updater.user_id = p.updated_by
left join lateral (
  select r.created_by, r.created_at
  from recipes r
  where r.product_id = p.id
    and r.is_active = true
  order by r.version desc, r.created_at desc
  limit 1
) active_recipe on true
left join profiles schema_actor on schema_actor.user_id = active_recipe.created_by
order by p.name;

grant select on product_catalog to anon, authenticated;

-- 3. Recreate supplier_raw_material_catalog view exposing latest received unit_price_ht
create or replace view supplier_raw_material_catalog as
select
  srm.supplier_id,
  p.id as product_id,
  p.code,
  p.name,
  p.type,
  p.unit,
  p.updated_at,
  latest_rec.unit_price_ht as latest_unit_price_ht
from supplier_raw_materials srm
join products p on p.id = srm.product_id
left join lateral (
  select r.unit_price_ht
  from raw_material_receptions r
  where r.product_id = p.id
    and r.unit_price_ht is not null
  order by r.reception_date desc, r.created_at desc
  limit 1
) latest_rec on true
where p.is_active = true
  and p.type = 'raw';

grant select on supplier_raw_material_catalog to anon, authenticated;

